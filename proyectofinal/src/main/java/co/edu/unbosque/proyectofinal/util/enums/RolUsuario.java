package co.edu.unbosque.proyectofinal.util.enums;

/**
 * Enumeración que representa los roles de un usuario en el sistema.
 * <p>
 * Define los tipos de permisos que puede tener un usuario dentro
 * de la plataforma de conversión de archivos.
 * </p>
 *
 * @author Equipo de desarrollo
 * @version 1.0
 */
public enum RolUsuario {

	/** Usuario con acceso básico para subir archivos y solicitar conversiones. */
	USUARIO,

	/** Usuario con acceso administrativo para gestionar usuarios y conversiones. */
	ADMIN
}
