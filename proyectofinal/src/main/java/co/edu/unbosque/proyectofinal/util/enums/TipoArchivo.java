package co.edu.unbosque.proyectofinal.util.enums;

/**
 * Enumeración que representa los tipos de archivo soportados
 * por la plataforma de conversión.
 * <p>
 * Cada valor corresponde a una categoría de archivo que el usuario
 * puede seleccionar para convertir.
 * </p>
 *
 * @author Equipo de desarrollo
 * @version 1.0
 */
public enum TipoArchivo {

	/** Archivos de audio (mp3, wav, aac, flac, ogg, m4a). */
	AUDIO,

	/** Archivos de video (mp4, mkv, avi, mov, webm, flv). */
	VIDEO,

	/** Archivos de imagen (jpg, png, webp, gif, bmp, tiff). */
	IMAGEN
}
